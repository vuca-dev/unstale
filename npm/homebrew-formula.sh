#!/usr/bin/env bash
# Writes the Homebrew formula for a release to stdout. The formula installs the same binaries as npm: it downloads
# each platform package's tarball from the npm registry (public even while this repository is private), so it is
# valid only once those packages are published. Windows has no Homebrew; win32-x64 is not in the formula.
#   npm/homebrew-formula.sh <dist dir> <homepage>    # dist dir holds unstale-cli-<key>-<version>.tgz for each key
# The tarball registry serves is the one `npm publish` uploaded, so the sha256 of the local .tgz is the download's.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
dist="$1"
homepage="$2"

version="$(sed -n 's/^version = "\(.*\)"/\1/p' "$root/local/cli/Cargo.toml" | head -1)"
license="$(node -p "require('$here/unstale/package.json').license")"
# Homebrew takes an SPDX id; anything else (UNLICENSED, "SEE LICENSE IN ...") cannot be represented.
case "$license" in
  UNLICENSED | SEE\ LICENSE*) license_line="license :cannot_represent" ;;
  *) license_line="license \"$license\"" ;;
esac

# url and sha256 lines for one platform package, indented for an on_<os> / on_<arch> block.
pkg() {
  local key="$1" tgz="$dist/unstale-cli-$1-$version.tgz"
  [ -f "$tgz" ] || { echo "missing $tgz" >&2; exit 1; }
  printf '      url "https://registry.npmjs.org/@unstale/cli-%s/-/cli-%s-%s.tgz"\n' "$key" "$key" "$version"
  printf '      sha256 "%s"\n' "$(shasum -a 256 "$tgz" | cut -d' ' -f1)"
}

cat <<EOF
# Generated by npm/homebrew-formula.sh for unstale $version; edits are overwritten on the next release.
class Unstale < Formula
  desc "Everything that changed past your coding agent's knowledge cutoff"
  homepage "$homepage"
  version "$version"
  $license_line

  on_macos do
    on_arm do
$(pkg darwin-arm64)
    end
    on_intel do
$(pkg darwin-x64)
    end
  end

  on_linux do
    on_arm do
$(pkg linux-arm64)
    end
    on_intel do
$(pkg linux-x64)
    end
  end

  def install
    bin.install "bin/unstale"
  end

  test do
    assert_equal "unstale #{version}", shell_output("#{bin}/unstale --version").strip
  end
end
EOF
